-- Create after API_KEY_AUTH has a NUMBER primary key; existing state must not be recreated.
CREATE TABLE API_KEY_ROTATION_STATE (
    SCOPE_ID VARCHAR2(6 BYTE) DEFAULT 'GLOBAL' NOT NULL,
    ACTIVE_KEY_ID NUMBER,
    GRACE_KEY_ID NUMBER,
    PENDING_KEY_ID NUMBER,
    NEXT_ROTATION_AT TIMESTAMP WITH TIME ZONE,
    PENDING_READY_AT TIMESTAMP WITH TIME ZONE,
    VERSION NUMBER(19, 0) DEFAULT 0 NOT NULL,
    LAST_OPERATION_ID VARCHAR2(64 BYTE),
    LAST_OPERATION_AT TIMESTAMP WITH TIME ZONE,
    CONSTRAINT PK_API_KEY_ROTATION_STATE PRIMARY KEY (SCOPE_ID),
    CONSTRAINT CK_API_KEY_STATE_SCOPE CHECK (SCOPE_ID = 'GLOBAL'),
    CONSTRAINT CK_API_KEY_STATE_VERSION CHECK (VERSION >= 0),
    CONSTRAINT CK_API_KEY_STATE_READY CHECK (
        PENDING_READY_AT IS NULL OR PENDING_KEY_ID IS NOT NULL
    ),
    CONSTRAINT CK_API_KEY_STATE_NEXT CHECK (
        ACTIVE_KEY_ID IS NULL OR NEXT_ROTATION_AT IS NOT NULL
    ),
    CONSTRAINT CK_API_KEY_STATE_OPERATION CHECK (
        (LAST_OPERATION_ID IS NULL AND LAST_OPERATION_AT IS NULL)
        OR (LAST_OPERATION_ID IS NOT NULL AND LAST_OPERATION_AT IS NOT NULL)
    ),
    CONSTRAINT CK_API_KEY_STATE_POINTERS CHECK (
        (ACTIVE_KEY_ID IS NULL OR GRACE_KEY_ID IS NULL OR ACTIVE_KEY_ID <> GRACE_KEY_ID)
        AND (ACTIVE_KEY_ID IS NULL OR PENDING_KEY_ID IS NULL OR ACTIVE_KEY_ID <> PENDING_KEY_ID)
        AND (GRACE_KEY_ID IS NULL OR PENDING_KEY_ID IS NULL OR GRACE_KEY_ID <> PENDING_KEY_ID)
    ),
    CONSTRAINT FK_API_KEY_STATE_ACTIVE FOREIGN KEY (ACTIVE_KEY_ID)
        REFERENCES API_KEY_AUTH (KEY_ID),
    CONSTRAINT FK_API_KEY_STATE_GRACE FOREIGN KEY (GRACE_KEY_ID)
        REFERENCES API_KEY_AUTH (KEY_ID),
    CONSTRAINT FK_API_KEY_STATE_PENDING FOREIGN KEY (PENDING_KEY_ID)
        REFERENCES API_KEY_AUTH (KEY_ID)
);
