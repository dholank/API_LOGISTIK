CREATE TABLE API_KEY_AUTH (
    KEY_ID NUMBER GENERATED ALWAYS AS IDENTITY,
    KEY_HASH VARCHAR2(64 BYTE) NOT NULL,
    STATUS VARCHAR2(10 BYTE) DEFAULT 'PENDING' NOT NULL,
    CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    ACTIVATES_AT TIMESTAMP WITH TIME ZONE,
    EXPIRES_AT TIMESTAMP WITH TIME ZONE,
    CONSTRAINT PK_API_KEY_AUTH PRIMARY KEY (KEY_ID),
    CONSTRAINT UK_API_KEY_AUTH_HASH UNIQUE (KEY_HASH),
    CONSTRAINT CK_API_KEY_AUTH_HASH CHECK (
        LENGTH(KEY_HASH) = 64
        AND TRANSLATE(KEY_HASH, 'x0123456789abcdef', 'x') IS NULL
    ),
    CONSTRAINT CK_API_KEY_AUTH_STATUS CHECK (
        STATUS IN ('PENDING', 'ACTIVE', 'GRACE', 'EXPIRED', 'REVOKED')
    ),
    CONSTRAINT CK_API_KEY_AUTH_LIVE_DATES CHECK (
        STATUS NOT IN ('ACTIVE', 'GRACE')
        OR (ACTIVATES_AT IS NOT NULL AND EXPIRES_AT IS NOT NULL)
    ),
    CONSTRAINT CK_API_KEY_AUTH_WINDOW CHECK (
        ACTIVATES_AT IS NULL
        OR EXPIRES_AT IS NULL
        OR EXPIRES_AT > ACTIVATES_AT
    )
);
