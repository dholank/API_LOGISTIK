SELECT
    SYS_CONTEXT('USERENV', 'SESSION_USER') AS SESSION_USER_NAME,
    SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AS CURRENT_SCHEMA_NAME,
    SYS_CONTEXT('USERENV', 'CON_NAME') AS CONTAINER_NAME,
    SYSTIMESTAMP AS DATABASE_TIME
FROM DUAL;

SELECT PRODUCT, VERSION, STATUS
FROM PRODUCT_COMPONENT_VERSION
WHERE PRODUCT LIKE 'Oracle Database%';

SELECT PARAMETER, VALUE
FROM NLS_DATABASE_PARAMETERS
WHERE PARAMETER IN ('NLS_CHARACTERSET', 'NLS_NCHAR_CHARACTERSET')
ORDER BY PARAMETER;

SELECT PRIVILEGE
FROM SESSION_PRIVS
ORDER BY PRIVILEGE;

SELECT ROLE
FROM SESSION_ROLES
ORDER BY ROLE;

-- Ownership and enabled-role grants must both be considered; an empty grant list is not denial proof.
SELECT OWNER, OBJECT_NAME, OBJECT_TYPE, STATUS
FROM ALL_OBJECTS
WHERE OBJECT_NAME IN (
    'KARYAWAN',
    'API_KEY_AUTH',
    'API_KEY_ROTATION_STATE',
    'F_CRUD_KARYAWAN_LOGISTIK',
    'F_VALIDATE_API_KEY_LOGISTIK',
    'P_PREPARE_API_KEY',
    'P_ROTATE_API_KEYS',
    'JOB_ROTATE_API_KEYS'
)
ORDER BY OWNER, OBJECT_NAME, OBJECT_TYPE;

SELECT OWNER, TABLE_NAME, COLUMN_ID, COLUMN_NAME, DATA_TYPE,
       DATA_LENGTH, DATA_PRECISION, DATA_SCALE, CHAR_USED, CHAR_LENGTH,
       NULLABLE, IDENTITY_COLUMN
FROM ALL_TAB_COLUMNS
WHERE TABLE_NAME IN ('KARYAWAN', 'API_KEY_AUTH', 'API_KEY_ROTATION_STATE')
ORDER BY OWNER, TABLE_NAME, COLUMN_ID;

SELECT OWNER, TABLE_NAME, COLUMN_NAME, GENERATION_TYPE
FROM ALL_TAB_IDENTITY_COLS
WHERE TABLE_NAME = 'API_KEY_AUTH'
ORDER BY OWNER, COLUMN_NAME;

SELECT OWNER, TABLE_NAME, CONSTRAINT_NAME, CONSTRAINT_TYPE,
       STATUS, VALIDATED, R_OWNER, R_CONSTRAINT_NAME, SEARCH_CONDITION_VC
FROM ALL_CONSTRAINTS
WHERE TABLE_NAME IN ('KARYAWAN', 'API_KEY_AUTH', 'API_KEY_ROTATION_STATE')
ORDER BY OWNER, TABLE_NAME, CONSTRAINT_NAME;

SELECT OWNER, TABLE_NAME, CONSTRAINT_NAME, COLUMN_NAME, POSITION
FROM ALL_CONS_COLUMNS
WHERE TABLE_NAME IN ('KARYAWAN', 'API_KEY_AUTH', 'API_KEY_ROTATION_STATE')
ORDER BY OWNER, TABLE_NAME, CONSTRAINT_NAME, POSITION;

SELECT GRANTEE, OWNER, TABLE_NAME, PRIVILEGE, GRANTABLE
FROM ALL_TAB_PRIVS_RECD
WHERE TABLE_NAME IN (
    'KARYAWAN',
    'API_KEY_AUTH',
    'API_KEY_ROTATION_STATE',
    'F_CRUD_KARYAWAN_LOGISTIK',
    'F_VALIDATE_API_KEY_LOGISTIK',
    'P_PREPARE_API_KEY',
    'P_ROTATE_API_KEYS'
)
ORDER BY OWNER, TABLE_NAME, GRANTEE, PRIVILEGE;

SELECT GRANTEE, OWNER, TABLE_NAME, COLUMN_NAME, PRIVILEGE, GRANTABLE
FROM ALL_COL_PRIVS_RECD
WHERE TABLE_NAME IN ('KARYAWAN', 'API_KEY_AUTH', 'API_KEY_ROTATION_STATE')
ORDER BY OWNER, TABLE_NAME, GRANTEE, COLUMN_NAME, PRIVILEGE;

-- Visible metadata cannot prove that writers in another schema or external host are absent.
SELECT OWNER, TRIGGER_NAME, TABLE_OWNER, TABLE_NAME, STATUS, TRIGGERING_EVENT
FROM ALL_TRIGGERS
WHERE TABLE_NAME IN ('KARYAWAN', 'API_KEY_AUTH', 'API_KEY_ROTATION_STATE')
ORDER BY TABLE_OWNER, TABLE_NAME, OWNER, TRIGGER_NAME;

SELECT OWNER, JOB_NAME, ENABLED, STATE, JOB_TYPE, REPEAT_INTERVAL,
       LAST_START_DATE, NEXT_RUN_DATE, FAILURE_COUNT
FROM ALL_SCHEDULER_JOBS
WHERE JOB_NAME = 'JOB_ROTATE_API_KEYS'
ORDER BY OWNER, JOB_NAME;

SELECT OWNER, OBJECT_NAME, ARGUMENT_NAME, POSITION, DATA_TYPE, IN_OUT, DEFAULTED
FROM ALL_ARGUMENTS
WHERE OBJECT_NAME = 'F_CRUD_KARYAWAN_LOGISTIK'
ORDER BY OWNER, SUBPROGRAM_ID, SEQUENCE;

SELECT OWNER, NAME, TYPE, LINE, POSITION, ATTRIBUTE, TEXT
FROM ALL_ERRORS
WHERE NAME = 'F_CRUD_KARYAWAN_LOGISTIK' AND TYPE = 'FUNCTION'
ORDER BY OWNER, SEQUENCE;
