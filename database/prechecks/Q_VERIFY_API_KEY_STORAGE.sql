-- Run after both tables exist, using the verified owner/schema; no key hashes are selected.
SELECT
    SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA') AS CURRENT_SCHEMA_NAME,
    SYSTIMESTAMP AS DATABASE_TIME
FROM DUAL;

SELECT
    COUNT(*) AS TOTAL_STATE_ROWS,
    COUNT(CASE WHEN SCOPE_ID = 'GLOBAL' THEN 1 END) AS GLOBAL_STATE_ROWS,
    CASE
        WHEN COUNT(*) = 1
         AND COUNT(CASE WHEN SCOPE_ID = 'GLOBAL' THEN 1 END) = 1
        THEN 'ROW_PRESENT_VERIFY_CONSTRAINTS'
        ELSE 'STOP_REVIEW_STATE_INITIALIZATION'
    END AS STORAGE_CHECK
FROM API_KEY_ROTATION_STATE;

SELECT SCOPE_ID, ACTIVE_KEY_ID, GRACE_KEY_ID, PENDING_KEY_ID,
       NEXT_ROTATION_AT, PENDING_READY_AT, VERSION,
       LAST_OPERATION_ID, LAST_OPERATION_AT
FROM API_KEY_ROTATION_STATE
ORDER BY SCOPE_ID;

WITH POINTERS AS (
    SELECT 'ACTIVE' AS POINTER_ROLE, ACTIVE_KEY_ID AS KEY_ID
    FROM API_KEY_ROTATION_STATE
    WHERE SCOPE_ID = 'GLOBAL'
    UNION ALL
    SELECT 'GRACE', GRACE_KEY_ID
    FROM API_KEY_ROTATION_STATE
    WHERE SCOPE_ID = 'GLOBAL'
    UNION ALL
    SELECT 'PENDING', PENDING_KEY_ID
    FROM API_KEY_ROTATION_STATE
    WHERE SCOPE_ID = 'GLOBAL'
)
SELECT P.POINTER_ROLE, P.KEY_ID, K.STATUS,
       CASE
           WHEN P.KEY_ID IS NULL THEN 'EMPTY'
           WHEN K.KEY_ID IS NULL THEN 'BROKEN_REFERENCE'
           WHEN K.STATUS = P.POINTER_ROLE THEN 'STATUS_MATCH_ONLY'
           ELSE 'STATUS_MISMATCH'
       END AS POINTER_CHECK
FROM POINTERS P
LEFT JOIN API_KEY_AUTH K ON K.KEY_ID = P.KEY_ID
ORDER BY P.POINTER_ROLE;

-- Counts may include legacy per-client rows; global membership is defined by state pointers.
SELECT STATUS, COUNT(*) AS KEY_ROWS
FROM API_KEY_AUTH
GROUP BY STATUS
ORDER BY STATUS;

SELECT TABLE_NAME, CONSTRAINT_NAME, CONSTRAINT_TYPE, STATUS, VALIDATED
FROM ALL_CONSTRAINTS
WHERE OWNER = SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA')
  AND TABLE_NAME IN ('API_KEY_AUTH', 'API_KEY_ROTATION_STATE')
ORDER BY TABLE_NAME, CONSTRAINT_NAME;
